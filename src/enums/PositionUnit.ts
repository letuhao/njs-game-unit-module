/**
 * Position unit enumeration
 * Defines the different types of position units
 */
export enum PositionUnit {
  PIXEL = 'pixel',
  PERCENT = 'percent',
  PARENT_WIDTH = 'parent-width',
  PARENT_HEIGHT = 'parent-height',
  VIEWPORT_WIDTH = 'viewport-width',
  VIEWPORT_HEIGHT = 'viewport-height',
  CENTER = 'center',
  LEFT = 'left',
  RIGHT = 'right',
  TOP = 'top',
  BOTTOM = 'bottom'
}
